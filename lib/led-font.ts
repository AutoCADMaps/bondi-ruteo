const BIG: Record<string, { w: number; rows: number[] }> = {}
for (const [k, rows] of Object.entries(GLYPHS)) BIG[k] = { w: 5, rows }

export type LedFontId = "5x7" | "5p"

export const LED_FONTS: Record<LedFontId, { h: number; glyphs: Record<string, { w: number; rows: number[] }> }> = {
  "5x7": { h: 7, glyphs: BIG },
  "5p": { h: 5, glyphs: SMALL },
}

// Los diseños viejos guardaron "3x5" para la fuente chica.
export function resolveLedFont(id: string | undefined): LedFontId {
  return id === "5x7" ? "5x7" : id ? "5p" : "5x7"
}

const ACCENTS: Record<string, [string, "acute" | "tilde" | "diaer"]> = {
  Á: ["A", "acute"], É: ["E", "acute"], Í: ["I", "acute"], Ó: ["O", "acute"], Ú: ["U", "acute"],
  Ñ: ["N", "tilde"], Ü: ["U", "diaer"],
}

// Fila extra de arriba para el acento, según el ancho de la letra.
function accentBits(kind: "acute" | "tilde" | "diaer", w: number): number {
  const bit = (c: number) => 1 << (w - 1 - Math.min(w - 1, Math.max(0, c)))
  if (kind === "acute") return bit(Math.floor(w / 2))
  if (kind === "diaer") return w <= 2 ? bit(0) | bit(1) : bit(0) | bit(w - 1)
  return w <= 2 ? bit(0) | bit(1) : bit(1) | bit(2)
}

export interface Glyph {
  w: number
  rows: number[]
  top: number
}

export function glyphFor(ch: string, font: LedFontId = "5x7"): Glyph {
  const defs = LED_FONTS[font].glyphs
  let c = ch.toUpperCase()
  if (c === "º") c = "°"
  if (defs[c]) return { ...defs[c], top: 0 }
  const acc = ACCENTS[c]
  if (acc) {
    const base = defs[acc[0]]
    return { ...base, top: accentBits(acc[1], base.w) }
  }
  return { ...defs[" "], top: 0 }
}
